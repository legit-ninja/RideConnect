#!/usr/bin/env python3
"""Render deploy/env.*.sh into app .env files.

Modes:
  next  — escape $ for Next.js dotenv-expand
  api   — plain values for pydantic-settings / python-dotenv
"""
from __future__ import annotations

import os
import re
import sys
import tempfile
from pathlib import Path


def parse_env_file(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw_line in path.read_text().splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$", line)
        if not match:
            continue
        key, val = match.group(1), match.group(2)
        if (val.startswith('"') and val.endswith('"')) or (
            val.startswith("'") and val.endswith("'")
        ):
            val = val[1:-1]
        values[key] = val
    return values


def escape_dotenv_value(value: str) -> str:
    # Next.js @next/env runs dotenv-expand; \$ becomes a literal $ at runtime.
    return value.replace("\\", "\\\\").replace("$", "\\$")


def render_env(values: dict[str, str], *, mode: str) -> str:
    lines = [
        f"# Generated by scripts/render-app-env.py ({mode}) — do not edit on server.",
        "# Source: deploy/env.<target>.sh",
        "",
    ]
    for key in sorted(values):
        val = values[key]
        if mode == "next":
            val = escape_dotenv_value(val)
        lines.append(f"{key}={val}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 4:
        print(
            f"Usage: {sys.argv[0]} <next|api> <input-env.sh> <output-.env>",
            file=sys.stderr,
        )
        return 1

    mode = sys.argv[1]
    if mode not in ("next", "api"):
        print("mode must be 'next' or 'api'", file=sys.stderr)
        return 1

    src = Path(sys.argv[2])
    dest = Path(sys.argv[3])
    if not src.is_file():
        print(f"Missing input file: {src}", file=sys.stderr)
        return 1

    content = render_env(parse_env_file(src), mode=mode)
    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(
        dir=dest.parent, prefix=f".{dest.name}.", suffix=".tmp"
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
        os.chmod(tmp_path, 0o600)
        os.replace(tmp_path, dest)
    except Exception:
        os.unlink(tmp_path)
        raise
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
